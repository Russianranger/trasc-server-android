def pe(patched=False):
    raw = bytearray(512)
    raw[:2] = b'MZ'
    struct.pack_into('<I', raw, 0x3c, 64)
    raw[64:68] = b'PE\0\0'
    struct.pack_into('<HH', raw, 68, 0x14c, 1)
    struct.pack_into('<HHH', raw, 84, 224, 0x0103 | (0x20 if patched else 0), 0x10b)
    raw[312:317] = b'.text'
    struct.pack_into('<II', raw, 328, 128, 384)
    raw[384:] = bytes(range(128))
    return bytes(raw)


class ConnectionTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.work = Path(self.temp.name)
        self.engine = types.SimpleNamespace(work=self.work, profile='custom')
        self.client = self.work/'client/current'
        self.client.mkdir(parents=True)
        self.marker = self.client/'trasc-client.json'
        self.marker.write_text(json.dumps({'executable': 'eqgame.exe', 'imported': True, 'imported_at': 12345}))
        self.exe = self.client/'eqgame.exe'
        self.exe.write_bytes(pe())
        self.exe.chmod(0o755)
        self.host = self.client/'eqhost.txt'

    def state(self):
        return connection.status(self.engine)

    def mutate(self, operation, **args):
        kind = 'host' if operation.startswith('client_host_') else 'patch'
        return connection.mutate(self.engine, operation, dict(revision=self.state()[kind]['revision'], **args))

    def records(self):
        return list((self.work/connection.RECOVERY).glob('*.json'))

    def test_read_is_nonmutating_and_missing_txt_defaults_to_local(self):
        (self.client/'eqhost.ini').write_bytes(b'Do not edit this file')
        state = self.state()
        self.assertEqual((state['host']['host'], state['host']['port'], state['host']['revision']), ('127.0.0.1', 5999, 'missing'))
        self.assertTrue(state['host']['can_save'])
        self.assertFalse(self.host.exists())
        self.assertFalse((self.work/'backups').exists())
        self.mutate('client_host_save', host='192.168.0.10')
        self.assertEqual(self.host.read_bytes(), b'[LoginServer]\r\nHost=192.168.0.10:5999\r\n')
        self.assertEqual((self.client/'eqhost.ini').read_bytes(), b'Do not edit this file')
        self.assertTrue(self.state()['host']['can_restore'])
        self.mutate('client_host_restore')
        self.assertFalse(self.host.exists())
        self.assertTrue(self.records())

    def test_address_change_preserves_every_other_byte_and_original(self):
        original = b'\xef\xbb\xbf; caf\xe9\r\n[LoginServer]\r\n  hOsT \t=\told.example:05999  ; keep me\r\n[Other]\r\nHost=other:10\r\n'
        self.host.write_bytes(original)
        result = self.mutate('client_host_save', host='192.168.2.5')
        self.assertEqual(self.host.read_bytes(), original.replace(b'old.example', b'192.168.2.5'))
        self.assertTrue(result['host']['can_restore'])
        record = json.loads(self.records()[0].read_text())
        saved = self.work/record['backup']
        self.assertEqual(saved.read_bytes(), original)
        self.assertEqual(stat.S_IMODE(saved.stat().st_mode), 0o400)
        self.mutate('client_host_save', host='10.0.0.4')
        self.assertEqual(saved.read_bytes(), original)
        self.assertEqual(len(list((self.work/connection.RECOVERY).glob('*/original'))), 1)
        self.mutate('client_host_restore')
        self.assertEqual(self.host.read_bytes(), original)
        self.mutate('client_host_restore')
        self.assertEqual(self.host.read_bytes(), original)

    def test_noop_is_byte_exact_and_creates_no_backup(self):
        raw = b'[LoginServer]\nHost=127.0.0.1:06000\t# retained\n'
        self.host.write_bytes(raw)
        before = self.host.stat()
        self.mutate('client_host_save', host='127.0.0.1')
        self.assertEqual(self.host.read_bytes(), raw)
        self.assertEqual(self.host.stat().st_ino, before.st_ino)
        self.assertFalse((self.work/'backups').exists())

    def test_ipv6_preserves_port_and_invalid_host_is_rejected(self):
        self.host.write_bytes(b'[LoginServer]\nHost=127.0.0.1:5999\n')
        self.mutate('client_host_save', host='2001:db8::5')
        self.assertEqual(self.host.read_bytes(), b'[LoginServer]\nHost=[2001:db8::5]:5999\n')
        for invalid in ('host.example', '127.0.0.1:5999', '127.0.0.1\nHost=bad', '../eqgame.exe', 'fe80::1%eth0', None):
            with self.subTest(invalid=invalid), self.assertRaises(ValueError):
                self.mutate('client_host_save', host=invalid)

    def test_takp_updates_both_sections_and_preserves_independent_ports(self):
        self.engine.profile = 'takp'
        original = b'; comment\r\n[Registration Servers]\r\n{\r\n  "127.0.0.1:06000"\r\n}\r\n[Login Servers]\r\n{\r\n"127.0.0.1:6001" ; login\r\n}\r\n'
        self.host.write_bytes(original)
        result = self.mutate('client_host_save', host='192.168.5.3')
        self.assertEqual(self.host.read_bytes(), original.replace(b'127.0.0.1', b'192.168.5.3'))
        self.assertEqual(result['host']['port'], '06000, 6001')
        # Prepare is allowed to update marker validation fields without losing Restore.
        record = json.loads(self.marker.read_text());record['prepared_at'] = 67890
        self.marker.write_text(json.dumps(record))
        self.mutate('client_host_restore')
        self.assertEqual(self.host.read_bytes(), original)
        with self.assertRaisesRegex(ValueError, 'IPv4'):
            self.mutate('client_host_save', host='::1')

    def test_prepare_only_seeds_missing_txt_for_every_profile(self):
        for profile, port in (('custom', 5999), ('traditional', 5999), ('takp', 6000)):
            self.engine.profile = profile
            self.host.unlink(missing_ok=True)
            changes = {}
            connection.prepare_default(self.engine, self.client, changes)
            self.assertIn(b'127.0.0.1:' + str(port).encode(), changes[self.host])
            original = b'Any imported bytes and custom host:9000\r\n'
            self.host.write_bytes(original)
            changes = {}
            connection.prepare_default(self.engine, self.client, changes)
            self.assertEqual(changes, {})
            self.assertEqual(self.host.read_bytes(), original)

    def test_takp_legacy_save_launch_repair_restore_and_relaunch_keep_recovery(self):
        import takp_client
        self.engine.profile = 'takp'
        original = takp_client.login_text('10.0.0.8', 6123).replace('Registration Servers', 'RegistrationServers').replace('Login Servers', 'LoginServers').encode()
        self.host.write_bytes(original)
        self.mutate('client_host_save', host='192.168.1.77')
        self.assertIn(b'[LoginServers]', self.host.read_bytes())
        prefix = self.work/'client/prefix'
        report = takp_client.repair_login_file(self.client, prefix)
        self.assertTrue(report['repaired'])
        self.assertTrue(self.state()['host']['can_restore'])
        self.assertTrue(self.state()['host']['can_save'])
        self.assertEqual(self.state()['host']['warning'], '')
        self.mutate('client_host_restore')
        self.assertEqual(self.host.read_bytes(), original)
        takp_client.repair_login_file(self.client, prefix)
        self.assertEqual(self.state()['host']['warning'], '')
        self.mutate('client_host_save', host='192.168.1.88')
        self.mutate('client_host_restore')
        self.assertEqual(self.host.read_bytes(), original)
        self.assertEqual(len(self.records()), 1)

    def test_host_casing_duplicates_and_malformed_file_are_safe(self):
        self.host = self.host.with_name('EQHOST.TXT')
        self.host.write_bytes(b'[LoginServer]\r\nHost=127.0.0.1:5999\r\n')
        self.mutate('client_host_save', host='10.2.3.4')
        self.assertFalse((self.client/'eqhost.txt').exists())
        (self.client/'eqhost.txt').write_bytes(self.host.read_bytes())
        self.assertFalse(self.state()['host']['can_save'])
        with self.assertRaises(ValueError):
            self.mutate('client_host_save', host='10.2.3.5')
        (self.client/'eqhost.txt').unlink()
        for malformed in (b'[LoginServer]\nHost=host:0\n', b'[LoginServer]\nHost=x:5999\nHost=y:5999\n', b'\xff\xfe\x00', b'Host=127.0.0.1:5999'):
            self.host.write_bytes(malformed)
            self.assertFalse(self.state()['host']['can_save'])
            with self.assertRaises(ValueError):
                self.mutate('client_host_save', host='10.2.3.5')
            self.assertEqual(self.host.read_bytes(), malformed)

    def test_patch_changes_only_laa_bit_is_idempotent_and_restore_exact(self):
        original = self.exe.read_bytes()
        self.mutate('client_4gb_apply')
        updated = self.exe.read_bytes()
        self.assertEqual([index for index, pair in enumerate(zip(original, updated)) if pair[0] != pair[1]], [86])
        self.assertEqual(updated[86], original[86] | 0x20)
        self.assertEqual(stat.S_IMODE(self.exe.stat().st_mode), 0o755)
        self.assertTrue(self.state()['patch']['patched'])
        records = self.records()
        self.mutate('client_4gb_apply')
        self.assertEqual(self.records(), records)
        self.assertEqual(len(list((self.work/connection.RECOVERY).glob('*/original'))), 1)
        self.mutate('client_4gb_restore')
        self.assertEqual(self.exe.read_bytes(), original)
        self.assertFalse(self.state()['patch']['patched'])
        self.mutate('client_4gb_apply')
        self.assertEqual(self.exe.read_bytes(), updated)

    def test_already_patched_import_creates_no_spurious_original(self):
        self.exe.write_bytes(pe(patched=True))
        self.mutate('client_4gb_apply')
        self.assertFalse((self.work/'backups').exists())
        self.assertFalse(self.state()['patch']['can_restore'])

    def test_patch_rejects_malformed_x64_dll_and_truncated_sections(self):
        cases = [b'MZ', b'x'*512]
        for offset, fmt, value in ((0x3c, '<I', 0xffffffff), (68, '<H', 0x8664), (88, '<H', 0x20b), (86, '<H', 0x2002), (328, '<I', 512), (70, '<H', 0)):
            raw = bytearray(pe());struct.pack_into(fmt, raw, offset, value);cases.append(bytes(raw))
        for raw in cases:
            self.exe.write_bytes(raw)
            with self.subTest(size=len(raw)), self.assertRaises(ValueError):
                self.mutate('client_4gb_apply')
            self.assertEqual(self.exe.read_bytes(), raw)
        self.assertFalse((self.work/'backups').exists())

    def test_traditional_and_takp_patch_are_refused(self):
        for profile in ('traditional', 'takp'):
            self.engine.profile = profile
            self.assertFalse(self.state()['patch']['eligible'])
            with self.assertRaisesRegex(ValueError, 'Custom'):
                connection.mutate(self.engine, 'client_4gb_apply', {'revision': connection.sha(pe())})

    def test_original_corruption_and_external_changes_refuse_restore(self):
        self.mutate('client_4gb_apply')
        record = json.loads(self.records()[0].read_text())
        saved = self.work/record['backup']
        saved.chmod(0o600);saved.write_bytes(b'corrupt')
        current = self.exe.read_bytes()
        with self.assertRaisesRegex(ValueError, 'checksum'):
            self.mutate('client_4gb_restore')
        self.assertEqual(self.exe.read_bytes(), current)
        saved.write_bytes(pe())
        changed = bytearray(current);changed[-1] ^= 1;self.exe.write_bytes(changed)
        with self.assertRaisesRegex(ValueError, 'outside'):
            self.mutate('client_4gb_restore')
        self.assertEqual(self.exe.read_bytes(), changed)

    def test_recovery_record_path_traversal_is_refused(self):
        self.mutate('client_4gb_apply')
        marker = self.records()[0]
        record = json.loads(marker.read_text());record['backup'] = '../../outside'
        marker.write_text(json.dumps(record))
        with self.assertRaisesRegex(ValueError, 'recovery path'):
            self.mutate('client_4gb_restore')

    def test_reimport_retains_old_original_and_backs_up_new_installation(self):
        self.mutate('client_4gb_apply')
        first = json.loads(self.records()[0].read_text())
        self.marker.write_text(json.dumps({'executable': 'eqgame.exe', 'imported': True, 'imported_at': 55555}))
        replacement = bytearray(pe());replacement[-1] = 250
        self.exe.write_bytes(replacement)
        self.assertFalse(self.state()['patch']['backup_exists'])
        self.mutate('client_4gb_apply')
        self.assertEqual(len(self.records()), 2)
        self.assertEqual((self.work/first['backup']).read_bytes(), pe())
        self.mutate('client_4gb_restore')
        self.assertEqual(self.exe.read_bytes(), replacement)

    def test_symlink_file_and_internal_linked_ancestors_are_refused(self):
        outside = self.work/'outside.txt';outside.write_bytes(b'[LoginServer]\nHost=127.0.0.1:5999\n')
        self.host.symlink_to(outside)
        with self.assertRaises(ValueError):
            self.mutate('client_host_save', host='10.1.2.3')
        self.host.unlink()
        backups = self.work/'real-backups';backups.mkdir()
        (self.work/'backups').symlink_to(backups)
        with self.assertRaisesRegex(ValueError, 'symbolic'):
            self.mutate('client_4gb_apply')
        self.assertEqual(self.exe.read_bytes(), pe())

    def test_stale_revision_and_active_client_lease_leave_files_unchanged(self):
        with self.assertRaisesRegex(ValueError, 'Reload'):
            connection.mutate(self.engine, 'client_4gb_apply', {'revision':'stale'})
        run = self.work/'run';run.mkdir()
        (run/'client-active.json').write_text(json.dumps({'pid':os.getpid()}))
        with self.assertRaisesRegex(ValueError, 'Stop the client'):
            self.mutate('client_4gb_apply')
        self.assertEqual(self.exe.read_bytes(), pe())
        (run/'client-active.json').write_text('{"pid":"bad"}')
        with self.assertRaisesRegex(ValueError, 'Invalid client runtime'):
            self.mutate('client_4gb_apply')
        (run/'client-active.json').write_text('{"pid":2147483647}')
        self.mutate('client_4gb_apply')

    def test_atomic_replacement_failure_keeps_original_and_recovery(self):
        original = os.replace
        def fail_client(source, destination):
            if Path(destination) == self.exe:
                raise OSError('simulated rename failure')
            return original(source, destination)
        with patch.object(connection.os, 'replace', side_effect=fail_client), self.assertRaises(OSError):
            self.mutate('client_4gb_apply')
        self.assertEqual(self.exe.read_bytes(), pe())
        self.assertTrue(self.state()['patch']['backup_exists'])
        self.mutate('client_4gb_apply')
        self.assertTrue(self.state()['patch']['can_restore'])

    def test_engine_dispatch_rejects_stale_profile_and_routes_operations(self):
        engine = Engine.__new__(Engine);engine.work = self.work;engine.profile = 'custom'
        state = engine.dispatch('client_connection_status', {'__profile':'custom'})
        self.assertTrue(state['patch']['can_apply'])
        with self.assertRaisesRegex(ValueError, 'World profile changed'):
            engine.dispatch('client_4gb_apply', {'__profile':'takp', 'revision':state['patch']['revision']})
        result = engine.dispatch('client_4gb_apply', {'__profile':'custom', 'revision':state['patch']['revision']})
        self.assertTrue(result['patch']['patched'])

    def test_engine_file_moves_cannot_remove_originals_or_write_recovery(self):
        self.mutate('client_4gb_apply')
        record = json.loads(self.records()[0].read_text())
        engine = Engine.__new__(Engine);engine.work = self.work;engine.db = None;engine.server_running = lambda: False
        with self.assertRaisesRegex(ValueError, 'protected'):
            engine.edit_file({'action':'move', 'path':record['backup'], 'destination':'exports/original.exe'})
        with self.assertRaisesRegex(ValueError, 'protected'):
            engine.edit_file({'action':'move', 'path':'backups', 'destination':'exports/backups'})
        incoming = self.work/'incoming';incoming.mkdir();(incoming/'fake').write_bytes(b'fake')
        with self.assertRaisesRegex(ValueError, 'protected'):
            engine.edit_file({'action':'copy', 'path':'incoming/fake', 'destination':connection.RECOVERY+'/replacement'})
        self.assertEqual((self.work/record['backup']).read_bytes(), pe())

